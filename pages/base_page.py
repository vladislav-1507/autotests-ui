from playwright.sync_api import Page


class BasePage:
    def __init__(self, page: Page):
        self.page = page

    def visit(self, url: str):
        self.page.goto(url, wait_until="networkidle")

    def reload(self):
        self.page.reload(wait_until="domcontentloaded")


"""
Как работает эта архитектура?

1. BasePage — это "фундамент".
   - Он не знает о конкретных элементах на страницах (кнопках, полях ввода).
   - Его главная задача — хранить в себе `self.page` (объект страницы из Playwright).
   - Он предоставляет общие для всех страниц методы (`visit`, `reload`), 
   которые используют `self.page`.

2. LoginPage, CoursesListPage и т.д. — это "комнаты" (конкретные страницы).
   - Они наследуются от `BasePage`.
   - Они знают о своих уникальных элементах (`email_input`, `login_button` и т.д.).
   - При создании (в `__init__`) они принимают объект `page` и передают его 
   "вверх" в конструктор `BasePage` через `super().__init__(page)`.

3. Фикстуры в `fixtures/pages.py` (например, `login_page`) — это "фабрики" 
объектов страниц.
   - Они не являются страницами сами по себе.
   - Их задача — взять "сырой" объект страницы `page` (полученный из фикстур в 
   `fixtures/browsers.py`) и создать из него готовый к работе объект, например, 
   `LoginPage(page=...)`.

4. Фикстуры в `fixtures/browsers.py` (например, `chromium_page`) — это "поставщики" 
браузерных страниц.
   - Они запускают браузер, создают новую страницу (`Page`) и передают ее тем 
   фикстурам, которые ее запрашивают.

Цепочка вызовов в тесте:

Когда вы в тесте вызываете, например, `login_page.visit(...)`:

1. Вы обращаетесь к объекту `LoginPage`, который создала фикстура `login_page`.
2. У `LoginPage` нет своего метода `visit`, поэтому Python ищет его у 
родителя — `BasePage`.
3. Находится метод `BasePage.visit()`.
4. Этот метод обращается к `self.page` (который был сохранен при создании 
объекта `LoginPage`) и вызывает у него метод `goto()`.

Таким образом, фикстуры `pytest` организуют создание и внедрение зависимостей 
(dependency injection), передавая объект `page` от создателя (фикстура браузера) 
к потребителю (ваш Page Object).
"""
